-- ============================================================
-- 083 — Blended admin schema: the postgame1.com admin's tables, rebuilt
-- inside the Hub as EMPTY tables (structure only, no data).
--
-- Blueprint: "Admin -> Hub: Rebuild Map" doc, Blended blueprint tab (2026-10-17).
--   * Legacy ColdFusion tables get real types (true/false, numbers, dates) and
--     real links: athletes -> people.id, brands -> brands.id,
--     campaigns -> campaigns.campaign_id (the ColdFusion campaign number).
--   * The admin's "side tables" (built only to survive the nightly wipe) are
--     folded back into their main table (campaigns, brands, campaign_opt_ins,
--     campaign_storage, campaign_athlete_folders).
--   * No SSNs, tax IDs, bank/routing numbers or passwords anywhere.
--   * Existing Hub tables only GAIN nullable/defaulted columns; no data changes.
--   * Drops the old `campaigns` VIEW (a re-select of campaign_recaps). Before
--     this reaches production, repoint src/app/clients/[slug]/page.tsx and
--     src/app/dashboard/website/page.tsx at campaign_recaps.
--
-- APPLIED to the practice branch recap-editor-test (jlxdxuqfmnnpwvmozgmm) on 2026-10-19 only.
-- NOT applied to production (xqaybwhpgxillpbbqtks).
-- ============================================================

do $$ begin
  if exists (select 1 from pg_class c join pg_namespace n on n.oid=c.relnamespace
             where n.nspname='public' and c.relname='campaigns' and c.relkind='v') then
    drop view public.campaigns;
  end if;
end $$;

